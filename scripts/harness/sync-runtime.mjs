#!/usr/bin/env node
// Copy Typora's extension runtime into the harness, from the Typora monorepo
// this repository sits in (extensions/ next to packages/). The store's CI has
// no monorepo, so the output is committed; run this after the runtime changes:
//
//   node extensions/scripts/harness/sync-runtime.mjs
//
// - extension-worker.js  the Worker bootstrap (global allowlist, SDK)
// - view.js              the page SDK, served as __typora/view.js
// - sanitize.js          what Typora does to a fence renderer's output
// - csp.json             the page and Worker CSPs, with {base} for the extension's origin

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const monorepo = join(here, "..", "..", "..");
const require = createRequire(join(monorepo, "package.json"));
const { transformSync } = require("esbuild");

const SOURCES = {
  "extension-worker.js": "packages/workbench/src/extensions/worker/bootstrap.ts",
  "view.js": "packages/workbench/src/extensions/view/viewSdk.ts",
  "sanitize.js": "packages/workbench/src/extensions/sanitize.ts",
};

let commit = "unknown";
try {
  commit = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: monorepo, encoding: "utf8" }).trim();
} catch {}

for (const [name, source] of Object.entries(SOURCES)) {
  const { code } = transformSync(readFileSync(join(monorepo, source), "utf8"), { loader: "ts", target: "es2022", sourcefile: source });
  writeFileSync(join(here, "runtime", name), `// Generated by scripts/harness/sync-runtime.mjs from ${source} (Typora ${commit}). Do not edit.\n${code}`);
  console.log(`✓ runtime/${name}`);
}

// The CSPs, read from the Electron protocol handler so they stay the same.
const protocol = readFileSync(join(monorepo, "apps/electron/src/main/extensionProtocol.ts"), "utf8");
const page = /export function extensionPageCsp[\s\S]*?return \[([\s\S]*?)\]\.join\("; "\)/.exec(protocol)?.[1];
const worker = /export function extensionWorkerCsp[\s\S]*?return `([^`]*)`/.exec(protocol)?.[1];
if (!page || !worker) throw new Error("Cannot find the CSPs in extensionProtocol.ts.");
const pageCsp = [...page.matchAll(/["`]([^"`]+)["`]/g)].map((m) => m[1].replace("${base}", "{base}")).join("; ");
const workerCsp = worker.replace("x-typora://ext/${id}/", "{base}");
writeFileSync(join(here, "runtime", "csp.json"), `${JSON.stringify({ source: `apps/electron/src/main/extensionProtocol.ts (Typora ${commit})`, page: pageCsp, worker: workerCsp }, null, 2)}\n`);
console.log("✓ runtime/csp.json");
